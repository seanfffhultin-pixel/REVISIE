// Run with Playwright available in NODE_PATH: node tests/subject-editing-browser.cjs
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const root = path.resolve(__dirname, '..');
(async () => {
  const browser = await chromium.launch();
  try {
    const context = await browser.newContext({ reducedMotion: 'reduce', viewport: { width: 1440, height: 1000 } });
    await context.route('**/*', route => {
      const url = new URL(route.request().url());
      if (url.hostname !== 'revisie.test') return route.abort();
      const file = path.resolve(root, '.' + decodeURIComponent(url.pathname));
      if (!file.startsWith(root + path.sep) || !fs.existsSync(file)) return route.fulfill({ status: 404, body: 'Missing asset' });
      return route.fulfill({ path: file, contentType: { '.html': 'text/html', '.css': 'text/css', '.js': 'text/javascript', '.png': 'image/png' }[path.extname(file)] });
    });
    const page = await context.newPage(); const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const goto = file => page.goto(`https://revisie.test/${file}.html`);
    const openSubjectOptions = async key => page.locator(`[data-subject-card="${key}"]`).locator('..').locator('.item-actions > summary').click();
    await goto('subjects');
    await openSubjectOptions('biology');
    await page.locator('[data-subject-board="biology"]').click();
    assert.equal(await page.locator('#subjectBoard').inputValue(), 'AQA');
    await page.locator('#subjectBoard').fill('OCR');
    await page.locator('.modal [type="submit"]').click();
    assert.match(await page.locator('[data-subject-card="biology"]').innerText(), /OCR/);
    await page.reload();
    assert.match(await page.locator('[data-subject-card="biology"]').innerText(), /OCR/);
    await goto('biology');
    assert.equal(await page.locator('.page-intro .eyebrow').innerText(), 'GCSE HIGHER · OCR');
    await page.locator('[data-subject-board="biology"]').click();
    await page.locator('#subjectBoard').fill('My custom board <2026>');
    await page.locator('.modal [type="submit"]').click();
    assert.equal(await page.locator('.page-intro .eyebrow').innerText(), 'GCSE HIGHER · My custom board <2026>');
    const original = await page.locator('[data-edit-topic]').first().getAttribute('data-edit-topic');
    const other = await page.locator('[data-edit-topic]').nth(1).getAttribute('data-edit-topic');
    const originalDeck = await page.evaluate(name => getDeck('biology', name), original);
    await page.evaluate(name => {
      userCards.push({subject:'biology',unit:name,question:'Personal question',answer:'Personal answer'});
      saveWorkspaceItem('revisie-flashcards',JSON.stringify(userCards));
      starterCardOverrides[`biology::${name}::0`]={question:'Edited starter',answer:'Edited starter answer'};
      saveWorkspaceItem('revisie-starter-card-overrides',JSON.stringify(starterCardOverrides));
      saveWorkspaceItem('revisie-topic-progress',JSON.stringify({[`biology::${name}`]:2}));
      saveWorkspaceItem('revisie-flashcard-drafts',JSON.stringify({[JSON.stringify(['biology',name])]:{question:'Unfinished question',answer:'Draft answer'}}));
      saveWorkspaceItem('revisie-card-destination',JSON.stringify({subject:'biology',unit:name}));
    }, original);
    await page.locator('.topic-actions summary').first().click();
    await page.locator('[data-edit-topic]:visible').click();
    await page.locator('#topicName').fill(other);
    await page.locator('.modal [type="submit"]').click();
    assert.equal(await page.locator('#topicName').evaluate(el=>el.checkValidity()),false);
    const renamed='Cells & microscopy <revision>';
    await page.locator('#topicName').fill(renamed);
    await page.locator('.modal [type="submit"]').click();
    await page.reload();
    assert.equal(await page.locator('.subject-card strong').first().innerText(), renamed);
    const deck=await page.evaluate(name=>getDeck('biology',name),renamed);
    assert.equal(deck.length,originalDeck.length+1);
    assert.deepEqual(deck[0],['Edited starter','Edited starter answer']);
    assert.deepEqual(deck.at(-1),['Personal question','Personal answer']);
    assert.equal(await page.evaluate(name=>topicProgress()[`biology::${name}`],renamed),2);
    await page.locator('#subjectAddCard').click();
    assert.equal(await page.locator('#cardUnit').inputValue(),renamed);
    assert.equal(await page.locator('#cardQuestion').inputValue(),'Unfinished question');
    await page.keyboard.press('Escape');
    await goto('flashcards');
    const card=page.locator('.topic-card-wrap').filter({has:page.locator('[data-unit]').filter({hasText:renamed})});
    await card.locator('summary').click();
    await page.locator('[data-edit-topic]:visible').click();
    await page.locator('#topicName').fill('Renamed again');
    await page.locator('.modal [type="submit"]').click();
    await page.reload();
    assert.equal(await page.locator('[data-unit="Renamed again"]').count(),1);
    await goto('biology'); await page.locator('.topic-actions summary').first().click();
    page.once('dialog',dialog=>dialog.accept());
    await page.locator('[data-delete-topic]:visible').click();
    await page.reload();
    assert.equal(await page.locator('.topic-card-wrap').count(),2);
    assert.equal(await page.evaluate(name=>getDeck('biology',name).length,original),0);
    // Personal subjects have the same board control; custom topic editing still works.
    await goto('subjects'); await page.locator('#addSubject').click();
    await page.locator('#newSubject').fill('Economics'); await page.locator('#newTopic').fill('Markets');
    await page.locator('.modal [type="submit"]').click();
    await openSubjectOptions('economics'); await page.locator('[data-subject-board="economics"]').click();
    await page.locator('#subjectBoard').fill('Pearson Edexcel'); await page.locator('.modal [type="submit"]').click();
    await page.locator('[data-subject-card="economics"]').click();
    await page.locator('[data-subject-board="economics"]').waitFor();
    assert.equal(await page.locator('.page-intro .eyebrow').innerText(),'GCSE HIGHER · Pearson Edexcel');
    await page.evaluate(()=>{customTopics.economics=[{name:'Personal topic',cards:[['Original question','Original answer']]}];saveWorkspaceItem('revisie-topics',JSON.stringify(customTopics));refreshSubjectAppearance();});
    await page.locator('.topic-card-wrap').filter({hasText:'Personal topic'}).locator('summary').click();
    await page.locator('[data-edit-topic]:visible').click();
    await page.locator('#topicName').fill('Personal topic renamed'); await page.locator('.modal [type="submit"]').click();
    await page.reload();
    assert.deepEqual(await page.evaluate(()=>getDeck('economics','Personal topic renamed')),[['Original question','Original answer']]);
    await page.evaluate(()=>localStorage.setItem('revisie-account',JSON.stringify({name:'Sean'})));
    await goto('subjects');
    assert.equal(await page.locator('.workspace-switcher small').innerText(),'Personal Study Workspace');
    assert.deepEqual(errors,[], 'No browser errors');
    console.log('Passed subject exam boards, custom boards, default/custom topic renaming, duplicate validation, retained cards/progress/drafts, rename/delete persistence, and workspace wording.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
