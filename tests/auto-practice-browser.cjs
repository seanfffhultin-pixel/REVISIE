const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const root = path.resolve(__dirname, '..');
(async () => {
  const browser = await chromium.launch();
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
    await context.route('**/*', route => {
      const url = new URL(route.request().url());
      if (url.hostname !== 'revisie.test') return route.abort();
      const file = path.resolve(root, '.' + decodeURIComponent(url.pathname));
      if (!file.startsWith(root + path.sep) || !fs.existsSync(file)) return route.fulfill({ status: 404, body: 'Missing asset' });
      return route.fulfill({ path: file, contentType: { '.html': 'text/html', '.css': 'text/css', '.js': 'text/javascript', '.png': 'image/png' }[path.extname(file)] });
    });
    const page = await context.newPage(), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const goto = file => page.goto(`https://revisie.test/${file}`);
    await goto('biology.html');
    await page.locator('#subjectAddCard').click();
    await page.locator('#cardUnit').selectOption('__new__');
    await page.locator('#cardNewTopic').fill('My manually added topic');
    await page.locator('#cardQuestion').fill('Which structure contains genetic material?');
    await page.locator('#cardAnswer').fill('The nucleus.');
    await page.locator('[name="saveMode"][value="close"]').click();
    await goto('multiple-choice.html?subject=biology&topic=My%20manually%20added%20topic');
    assert.match(await page.locator('.practice-card').innerText(), /2 multiple-choice/);
    await page.locator('[data-start-subject]').click();
    assert.match(await page.locator('#practiceSession').innerText(), /Flashcard match/);
    assert.equal(await page.locator('.practice-options input').count(), 4);
    await page.locator('input[value="0"]').check();
    await page.locator('#practiceAnswer [type="submit"]').click();
    assert.match(await page.locator('#practiceFeedback').innerText(), /Correct/);
    await page.locator('#nextQuestion').click();
    await page.locator('input[value="0"]').check();
    await page.locator('#practiceAnswer [type="submit"]').click();
    await page.locator('#nextQuestion').click(); await page.locator('#finishPractice').click();
    await goto('short-answer.html?subject=biology&topic=My%20manually%20added%20topic');
    assert.match(await page.locator('.practice-card').innerText(), /1 short-answer/);
    const sibling = await context.newPage();
    await sibling.goto('https://revisie.test/short-answer.html?subject=biology&topic=My%20manually%20added%20topic');
    await page.evaluate(() => editFlashcard(userCards.findIndex(card => card.unit === 'My manually added topic'), 'biology', 'My manually added topic'));
    await page.locator('#cardAnswer').fill('The nucleus contains genetic material.');
    await page.locator('.modal [type="submit"]').click(); await page.locator('.modal-close').click();
    await sibling.locator('[data-start-subject]').click();
    await sibling.locator('#writtenAnswer').fill('Nucleus');
    await sibling.locator('#practiceAnswer [type="submit"]').click();
    assert.match(await sibling.locator('#practiceFeedback').innerText(), /The nucleus contains genetic material/);
    await sibling.close();
    await page.locator('#generateQuiz').click();
    assert.match(await page.locator('#generatedQuizPrompt').inputValue(), /The nucleus contains genetic material/);
    await page.locator('.modal-close').click();
    await goto('mathematics.html');
    await page.locator('#subjectAddCard').click();
    await page.locator('#cardUnit').selectOption('__new__');
    await page.locator('#cardNewTopic').fill('Linear equations and percentages');
    await page.locator('#cardQuestion').fill('How do you solve 2x + 4 = 10?');
    await page.locator('#cardAnswer').fill('Subtract 4 and divide by 2: x = 3.');
    await page.locator('[name="saveMode"][value="close"]').click();
    await page.locator('.practice-topic-links>div').filter({ hasText: 'Linear equations and percentages' }).getByText('Varied maths').click();
    await page.waitForLoadState();
    assert.equal(await page.locator('#mathsSubjectTopics .practice-card').count(), 1);
    assert.match(await page.locator('#mathsSubjectTopics').innerText(), /Percentages · Linear equations/);
    await page.locator('[data-configure-maths]').click();
    assert.equal(await page.locator('[name="mathsSkill"]:checked').count(), 2);
    await page.locator('[name="mathsSkill"][value="percentages"]').uncheck();
    await page.locator('.modal [type="submit"]').click();
    await page.reload();
    assert.match(await page.locator('#mathsSubjectTopics .practice-card').innerText(), /Linear equations/);
    assert.ok(!(await page.locator('#mathsSubjectTopics .practice-card p').innerText()).includes('Percentages'));
    await page.locator('[data-start-maths-subject]').click();
    const prompts = [];
    for (let i = 0; i < 10; i++) {
      const prompt = await page.locator('#practiceSession h3').innerText(); prompts.push(prompt);
      const [a, b, c] = prompt.match(/-?\d+/g).map(Number);
      const answer = prompt.startsWith('A number') ? (c - b) * a : prompt.includes('−') ? (c + b) / a : (c - b) / a;
      await page.locator('#writtenAnswer').fill(String(answer));
      await page.locator('#practiceAnswer [type="submit"]').click();
      assert.match(await page.locator('#practiceFeedback').innerText(), /Correct/);
      await page.locator('#nextQuestion').click();
    }
    assert.equal(new Set(prompts).size, 10);
    assert.ok(prompts.some(prompt => prompt.startsWith('A number')));
    assert.ok(prompts.some(prompt => prompt.includes('−')));
    assert.ok(prompts.some(prompt => prompt.startsWith('Solve') && prompt.includes('+')));
    await page.locator('#finishPractice').click();
    await page.locator('[data-start-maths-subject]').click();
    assert.ok(!prompts.includes(await page.locator('#practiceSession h3').innerText()));
    await page.locator('.modal-close').click();
    await goto('mathematics.html');
    await page.evaluate(() => editTopic('mathematics', 'Linear equations and percentages'));
    await page.locator('#topicName').fill('My renamed maths topic');
    await page.locator('.modal [type="submit"]').click();
    await goto('maths-practice.html?subject=mathematics&topic=My%20renamed%20maths%20topic');
    assert.equal(await page.locator('#mathsSubjectTopics .practice-card p').innerText(), 'Linear equations');
    await page.setViewportSize({ width: 320, height: 800 });
    await page.locator('[data-configure-maths]').click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: '/tmp/revisie-maths-topic-skills.png', fullPage: true });
    await page.locator('.modal-close').click();
    await goto('mathematics.html');
    page.once('dialog', dialog => dialog.accept());
    await page.evaluate(() => deleteTopic('mathematics', 'My renamed maths topic'));
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('revisie-maths-topic-skills')).length), 0);
    assert.deepEqual(errors, []);
    console.log('Automatic practice passed: manual topics/cards, immediate MC and SA, live edits across tabs, flashcard prompts, maths skill inference, configuration, variation, recent-question avoidance, rename/delete and mobile.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
